def populate(conn, specs):
    """Insert all specs into the database."""
    cursor = conn.cursor()
    for ds, s in specs.items():
        cursor.execute("""
            INSERT OR REPLACE INTO design_series_specs
            (design_series, thermal_power_mwth, fuel_type, moderator, coolant,
             number_of_coolant_loops, operating_pressure_bar, enrichment_pct,
             core_height_m, core_diameter_m, number_of_fuel_assemblies,
             number_of_control_elements, outlet_temperature_c, inlet_temperature_c,
             number_of_steam_generators, fuel_assembly_type, average_burnup_mwd_per_t, source)
            VALUES (?, ?, ?, ?, ?, ?, ?, ?, ?, ?, ?, ?, ?, ?, ?, ?, ?, ?)
        """, (ds, s.get('thermal_power_mwth'), s.get('fuel_type'), s.get('moderator'),
              s.get('coolant'), s.get('number_of_coolant_loops'), s.get('operating_pressure_bar'),
              s.get('enrichment_pct'), s.get('core_height_m'), s.get('core_diameter_m'),
              s.get('number_of_fuel_assemblies'), s.get('number_of_control_elements'),
              s.get('outlet_temperature_c'), s.get('inlet_temperature_c'),
              s.get('number_of_steam_generators'), s.get('fuel_assembly_type'),
              s.get('average_burnup_mwd_per_t'), s.get('source')))
    conn.commit()


def validate_keys(conn, specs):
    """Verify all spec keys match design_series_info entries."""
    cursor = conn.cursor()
    db_series = {row[0] for row in cursor.execute(
        "SELECT design_series FROM design_series_info"
    ).fetchall()}

    spec_keys = set(specs.keys())
    missing_from_specs = db_series - spec_keys
    extra_in_specs = spec_keys - db_series

    if missing_from_specs:
        print(f"\nWARNING: {len(missing_from_specs)} design series in DB but not in specs:")
        for m in sorted(missing_from_specs):
            print(f"  - {m}")

    if extra_in_specs:
        print(f"\nWARNING: {len(extra_in_specs)} design series in specs but not in DB:")
        for e in sorted(extra_in_specs):
            print(f"  - {e}")

    if not missing_from_specs and not extra_in_specs:
        print(f"\nAll {len(spec_keys)} design series match the database.")

    return missing_from_specs, extra_in_specs


def print_summary(conn):
    """Print coverage statistics."""
    cursor = conn.cursor()
    fields = ['thermal_power_mwth', 'fuel_type', 'moderator', 'coolant',
              'number_of_coolant_loops', 'operating_pressure_bar', 'enrichment_pct',
              'core_height_m', 'core_diameter_m', 'number_of_fuel_assemblies',
              'number_of_control_elements', 'outlet_temperature_c', 'inlet_temperature_c',
              'number_of_steam_generators', 'fuel_assembly_type', 'average_burnup_mwd_per_t']

    total = cursor.execute("SELECT COUNT(*) FROM design_series_specs").fetchone()[0]
    print(f"\nTotal design series: {total}")
    print(f"\nField coverage:")
    for field in fields:
        count = cursor.execute(
            f"SELECT COUNT(*) FROM design_series_specs WHERE {field} IS NOT NULL"
        ).fetchone()[0]
        pct = count / total * 100 if total > 0 else 0
        print(f"  {field}: {count}/{total} ({pct:.0f}%)")

    # Also show how many reactors are covered
    covered = cursor.execute("""
        SELECT COUNT(*) FROM reactors r
        JOIN design_series_specs dss ON r.design_series = dss.design_series
    """).fetchone()[0]
    total_reactors = cursor.execute("SELECT COUNT(*) FROM reactors").fetchone()[0]
    print(f"\nReactors with design specs: {covered}/{total_reactors}")


